# Regenerates mobilityid/iso3166_alpha2.go, the ISO 3166-1 alpha-2 codes accepted by CountryCode,
# from the JDK's Locale.getISOCountries() (the source the Scala reference validates against).
# Needs the Java version pinned in ../mise.toml. Usage, from go/: scripts/generate-iso3166.sh
