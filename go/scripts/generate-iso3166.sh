package mobilityid

HEADER
  printf '// iso3166Alpha2 lists the %s ISO 3166-1 alpha-2 codes returned by the JDK'"'"'s\n' "$count"
  printf '// Locale.getISOCountries(), the reference the Scala library validates country codes against.\n'
  printf 'var iso3166Alpha2 = map[string]struct{}{\n'
  printf '%s\n' "$codes" | awk '{ printf "\t\"%s\": {},\n", $1 }'
  printf '}\n'
} > "$out"

gofmt -l "$out" >/dev/null
echo "wrote $out ($count codes)"
